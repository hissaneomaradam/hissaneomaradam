const dictionaries = { en, fr };

const I18nContext = createContext<{ language: Language; setLanguage: (language: Language) => void; t: (key: string) => string }>({
  language: "en",
  setLanguage: () => undefined,
  t: (key) => key,
});

export function I18nProvider({ language, setLanguage, children }: { language: Language; setLanguage: (language: Language) => void; children: React.ReactNode }) {
  const t = (key: string) => dictionaries[language][key] ?? en[key] ?? key;
  return <I18nContext.Provider value={{ language, setLanguage, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
